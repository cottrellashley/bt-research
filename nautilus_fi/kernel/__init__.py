"""The research kernel: strategies as Python objects, any data source, one engine per fidelity.

Everything a PM or an agent changes is an object: data sources, fields and signals (expressions
evaluated over all dates at once), universes and indices, construction methods and an optimiser
written as expressions, execution, costs, financing, missing returns, excess returns, turnover and
metrics. A ``Strategy`` bundles them, is immutable and fingerprinted, and runs at Paper fidelity
(vectorised) or Implement fidelity (the event engine) with one result schema. Sessions count
every trial; ``compare(...).explain()`` says what a change did and why. See ``docs/kernel.md``.
"""

